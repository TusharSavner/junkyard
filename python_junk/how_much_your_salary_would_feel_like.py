#the core function tht does calculations
def convert(country_ini, country_end, salary):
    salary_end = salary * (ppp[country_end]/ppp[country_ini])
    local_value = salary_end * (currency_value[country_end]/currency_value[country_ini])
    if currency[country_ini] in suffix_symbol_currency:
        format_ini = f'{salary}{currency[country_ini]}'
        local_salary = f'{local_value}{currency[country_ini]}'
    else :
        format_ini = f'{currency[country_ini]}{salary}'
        local_salary = f'{currency[country_ini]}{local_value}'
    if currency[country_end] in suffix_symbol_currency:
        format_end = f'{salary_end}{currency[country_end]}'
    else:
        format_end = f'{currency[country_end]}{salary_end}'

    string = f"your salary of {format_ini} in {country_ini} would feel like {format_end} in {country_end} that's over {local_salary} "
    
   
    return string
